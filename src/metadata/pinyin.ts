let charMap: Map<string, string> | null = null

function getMap(): Map<string, string> {
  if (charMap) return charMap
  const map = new Map<string, string>()
  for (const [initial, chars] of Object.entries(INITIAL_GROUPS)) {
    for (const ch of chars) {
      if (!map.has(ch)) map.set(ch, initial)
    }
  }
  charMap = map
  return map
}

const CJK = /[\u3400-\u4dbf\u4e00-\u9fff]/

/**
 * 取中文串的拼音首字母。非汉字字符跳过，未收录的汉字跳过。
 * 「魂斗罗」→ 'hdl'
 */
export function pinyinInitials(text: string): string {
  if (!text) return ''
  const map = getMap()
  let out = ''
  for (const ch of text) {
    if (!CJK.test(ch)) continue
    const initial = map.get(ch)
    if (initial) out += initial
  }
  return out
}

/** 该字符串是否含有汉字 */
export function hasCjk(text: string): boolean {
  return CJK.test(text)
}
